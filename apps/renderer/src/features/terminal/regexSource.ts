/**
 * 文字を正規表現のソースへ埋め込む形に変換する。文字クラスの中身にも、連結したパターンにも
 * そのまま使える。呼び出し側は `u` か `v` フラグを付ける（`\u{...}` はフラグ無しだと
 * `u` の繰り返しとして別物に解釈され、構文エラーにもならず静かに壊れる）。
 *
 * 各文字を `\u{...}` に展開するのは、素のまま置けない記号が `v` モードで増えているため。
 * 文字クラス内の `/` `(` `)` `[` `]` `{` `}` `-` `\` `|` はエスケープが要り、`^^` `..` `::`
 * のような同一約物 2 連は集合演算として予約されている。集合を変えるたびにこの規則を
 * 意識せずに済ませる。桁数固定の `\uXXXX` ではなく `\u{...}` を使うのは、BMP 外の文字が
 * 静かに別の集合として解釈されるのを防ぐため。
 */
export function toRegExpSource(chars: Iterable<string>): string {
  return [...chars].map((char) => `\\u{${char.codePointAt(0)?.toString(16)}}`).join("");
}
